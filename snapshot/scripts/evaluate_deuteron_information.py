"""Preserve the existing AV18 S/D-to-b1 information through a quantum state.

Two runtimes may be used: build-reference needs existing LHAPDF bindings;
fit-reference needs the joint-learning extra. Both write one declared replay.
This is fixed radial-shape, two-channel information transfer, not a new
deuteron dynamics fit, a QCD matching calculation or a data prediction.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import numpy as np


def build_reference():
    import lhapdf
    from scipy.integrate import quad
    from deuteron_wigner.wavefunctions.av18 import load_av18_momentum
    from deuteron_wigner.collinear import (
        build_lf_smearing_spherical,b1_leading_order,ScalingVariable,
    )
    from deuteron_wigner.pdfs import LHAPDFProvider
    lhapdf.setVerbosity(0)
    source=Path('data/raw/av18/deut.wfk')
    wave=load_av18_momentum(source)
    radial=wave.radial_callable()
    upper=float(wave.grid[-1])
    norms=np.array([sum(quad(lambda k:k*k*radial(k)[i]**2,a,b,epsabs=1e-13)[0]
                         for a,b in zip(wave.grid[:-1],wave.grid[1:])) for i in (0,1)])
    target=np.sqrt(norms/norms.sum())
    def basis(c):
        def values(k):
            u,w=radial(k)
            return c[0]*u/np.sqrt(norms[0]),c[1]*w/np.sqrt(norms[1])
        return values
    pdf=LHAPDFProvider(set_name='NNPDF31_nnlo_as_0118_1000',member=0)
    x=np.array([.03,.05,.1,.2,.35,.5,.7])
    scale=np.sqrt(5.)
    resolutions=[]
    for nk,ncos in ((64,24),(128,32),(256,48)):
        smear=[];values=[]
        for c in ([1.,0.],[0.,1.],np.ones(2)/np.sqrt(2),target):
            s=build_lf_smearing_spherical(radial=basis(c),nucleon_mass=.93891897/.1973269804,
                                         k_max=upper,n_k=nk,n_cos_theta=ncos,n_phi=2)
            smear.append(s)
            values.append([b1_leading_order(x=float(z),scale=scale,flavors=(1,2,3),
                         charges={1:-1/3,2:2/3,3:-1/3},proton_pdf=pdf.proton,
                         neutron_pdf=pdf.neutron,smearing=s,
                         scaling_variable=ScalingVariable.NUCLEON,per_nucleon=True) for z in x])
        values=np.array(values)
        operators=np.zeros((len(x),2,2))
        operators[:,0,0],operators[:,1,1]=values[0],values[1]
        operators[:,0,1]=operators[:,1,0]=values[2]-(values[0]+values[1])/2
        predicted=np.einsum('i,xij,j->x',target,operators,target)
        # Spin-averaged smearing is insensitive to S/D relative sign at EVERY
        # node; b1 retains their tensor interference. No b1 fit is performed.
        u_cross=smear[2].unpolarized-(smear[0].unpolarized+smear[1].unpolarized)/2
        resolutions.append({'n_k':nk,'n_cos':ncos,'n_phi':2,
                            'b1_operators':operators.tolist(),'direct_b1':values[3].tolist(),
                            'operator_reconstruction_max_error':float(np.max(np.abs(predicted-values[3]))),
                            'unpolarized_interference_max':float(np.max(np.abs(u_cross))),
                            'norm':smear[3].unpolarized_norm(),'tensor_norm':smear[3].tensor_norm()})
    pdf_file=Path('data/raw/lhapdf/NNPDF31_nnlo_as_0118_1000/NNPDF31_nnlo_as_0118_1000_0000.dat')
    return {'scope':'preserved AV18 fixed-shape S/D and supplied nucleon PDFs; quantum information benchmark only',
            'wave_source':str(source),'wave_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
            'pdf_source':str(pdf_file),'pdf_sha256':hashlib.sha256(pdf_file.read_bytes()).hexdigest(),
            'lhapdf_version':lhapdf.version(),'pdf_set':'NNPDF31_nnlo_as_0118_1000','pdf_member':0,
            'pdf_caveat':'LO impulse formula with an NNLO PDF input is a preserved-input numerical control, not an order-consistent phenomenological prediction; no PDF/model uncertainties evaluated',
            'neutron':'isospin rotation of the proton PDF; not generated by new nucleon dynamics',
            'x_convention':'x_N, per_nucleon=True in existing collinear.py','x':x.tolist(),'Q_GeV':float(scale),
            'k_max_fm_inverse':upper,'tabulated_component_norms':wave.component_norms(),
            'pchip_component_norms':norms.tolist(),'target_state':target.tolist(),
            'normalization':'fixed finite-table PCHIP input normalized by its own total norm; no current rescaling',
            'resolutions':resolutions,
            'last_resolution_b1_max_change':float(np.max(np.abs(np.array(resolutions[-1]['direct_b1'])-resolutions[-2]['direct_b1']))),
            'learned_radial_shapes':False,'learned_hamiltonian':False,'physical_new_prediction':False}


def fit_reference(reference):
    import torch
    from deuteron_wigner.quantum.joint_state_dynamics import GraphState,REAL,COMPLEX
    graph=GraphState(['AV18_S_shape','AV18_D_shape'],[(0,1)])
    target=torch.tensor(reference['target_state'],dtype=COMPLEX)
    operators=torch.tensor(reference['resolutions'][-1]['b1_operators'],dtype=COMPLEX)
    rho0=torch.outer(target,target.conj())
    reference['fits']=[]
    for name,statefn in [('torch',graph.torch_state),('pennylane',graph.pennylane_state())]:
        angles=torch.nn.Parameter(torch.tensor([[-.8,.35]],dtype=REAL))
        optimizer=torch.optim.LBFGS([angles],max_iter=100,tolerance_grad=1e-12,tolerance_change=1e-16,line_search_fn='strong_wolfe')
        def closure():
            optimizer.zero_grad()
            psi=statefn(angles)
            # Complete supplied mixing/coherence information, not b1 data.
            loss=(torch.outer(psi,psi.conj())-rho0).abs().square().sum()
            loss.backward()
            return loss
        optimizer.step(closure)
        psi=statefn(angles)
        b1=torch.einsum('i,xij,j->x',psi.conj(),operators,psi).real
        direct=torch.tensor(reference['resolutions'][-1]['direct_b1'],dtype=REAL)
        gradient=torch.autograd.grad(b1.square().sum(),angles)[0]
        reference['fits'].append({'backend':name,'density_error':float(torch.linalg.norm(torch.outer(psi,psi.conj())-rho0).detach()),
                                 'angles':angles.detach().tolist(),'withheld_b1':b1.detach().tolist(),
                                 'withheld_b1_max_error':float(torch.max(torch.abs(b1-direct)).detach()),
                                 'b1_gradient':gradient.detach().tolist()})
    flipped=target*torch.tensor([1.,-1.],dtype=COMPLEX)
    b1_flipped=torch.einsum('i,xij,j->x',flipped.conj(),operators,flipped).real
    b1_true=torch.einsum('i,xij,j->x',target.conj(),operators,target).real
    reference['phase_erasure_control']={
        'same_S_D_probabilities':True,'same_unpolarized_smearing':True,
        'flipped_b1':b1_flipped.tolist(),'b1_max_change':float(torch.max(torch.abs(b1_flipped-b1_true))),
        'interpretation':'radial probabilities/unpolarized forward PDFs do not fix the tensor interference; no claim that b1 alone determines every complex phase'}
    return reference


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--build-reference',action='store_true')
    mode.add_argument('--fit-reference',type=Path)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    result=build_reference() if args.build_reference else fit_reference(json.loads(args.fit_reference.read_text()))
    args.output.write_text(json.dumps(result,indent=2,allow_nan=False)+'\n')
    print('Wrote',args.output)
